// The colour family of a row's round icon disc on My profile.

/// Which colours a row's icon disc uses.
enum ProfileRowTone {
  /// Solid Igongo red disc with a light icon (the activity rows' first row).
  solid,

  /// Soft red tint with a red icon (most activity rows).
  soft,

  /// Neutral grey disc with a muted icon (the account and security rows).
  neutral,

  /// Light red disc with a red icon, for the delete row.
  danger,
}
