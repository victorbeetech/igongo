// Copies the brand kit files the web needs (logos, fonts, card, favicons,
// manifest icons and the sharing image) from packages/brand into
// public/brand, before every dev run and build. The copies are not committed:
// packages/brand stays the only source (brand rule 1).

import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Step 1: work out the folders from this script's own place in the repo.
const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const brand = join(web, "../../packages/brand");
const out = join(web, "public/brand");

// Step 2: start clean, so a file removed from the kit is removed here too.
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

// Step 3: copy only what the web uses.
for (const folder of ["logo/mark", "logo/horizontal", "logo/stacked", "logo/spiral", "fonts", "cards/portrait-black", "web", "pattern", "illustrations"]) {
  cpSync(join(brand, folder), join(out, folder), { recursive: true, filter: (src) => !src.endsWith(".pdf") });
}

// Step 4: the state illustrations as a TypeScript module, so the page can put
// the SVG inline and tint its `currentColor` lines from the theme (an <img>
// cannot). The module is committed, so lint and type checks work without a build.
const drawings = join(brand, "illustrations");
const entries = readdirSync(drawings)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => `  ${JSON.stringify(f.replace(".svg", ""))}: ${JSON.stringify(readFileSync(join(drawings, f), "utf8").trim())},`);
writeFileSync(
  join(web, "src/shared/ui/illustration/illustrations.g.ts"),
  "// GENERATED by scripts/sync-brand.mjs from packages/brand/illustrations. Do not edit.\n" +
    "// The brand kit's state illustrations, by name, as SVG text.\n\n" +
    `export const ILLUSTRATIONS = {\n${entries.join("\n")}\n} as const;\n\n` +
    "/** The name of one illustration, such as \"empty\" or \"not-found\". */\n" +
    "export type IllustrationKind = keyof typeof ILLUSTRATIONS;\n",
);
