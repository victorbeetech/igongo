"""Contrast check: every colour pair of the Igongo theme, in light and dark mode.

Reads the one theme file (packages/design-tokens/tokens.json) and the list of
pairs the app and web really draw (tools/contrast-check/pairs.json), works out
each WCAG 2.2 contrast ratio, writes the report docs/design/contrast-report.md
and exits with an error if any pair is below its minimum. Run it from the
repository root after any change to the tokens:

    python3 tools/contrast-check/check_contrast.py .

A failing pair is fixed in tokens.json only, never in a screen, so the fix
reaches every screen of the app and the web at once.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

MODES = ("light", "dark")


def channels(hex_colour: str) -> list[int]:
    """Split "#RRGGBB" into its red, green and blue values (0 to 255)."""
    h = hex_colour.lstrip("#")
    return [int(h[i : i + 2], 16) for i in (0, 2, 4)]


def luminance(hex_colour: str) -> float:
    """The WCAG relative luminance of a colour, from 0 (black) to 1 (white)."""
    # Step 1: each channel to 0..1, then from sRGB to linear light.
    linear = []
    for value in channels(hex_colour):
        c = value / 255
        linear.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    # Step 2: weight the channels by how bright the eye sees them.
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def ratio(a: str, b: str) -> float:
    """The WCAG contrast ratio between two colours, from 1 to 21."""
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def blend(fg: str, bg: str, alpha: float) -> str:
    """The colour seen when fg is painted at opacity alpha over bg (chips, banners)."""
    mixed = [round(f * alpha + b * (1 - alpha)) for f, b in zip(channels(fg), channels(bg), strict=True)]
    return "#" + "".join(f"{v:02X}" for v in mixed)


def check(colours: dict, pair: dict) -> tuple[str, str, float]:
    """Return the drawn foreground, the drawn background and the ratio of one pair."""
    fg = colours[pair["fg"]]
    bg = colours[pair["bg"]]
    # A tinted background is the tint colour (the foreground unless named) over the base.
    if "tint" in pair:
        bg = blend(colours[pair.get("tintOf", pair["fg"])], bg, pair["tint"])
    return fg, bg, ratio(fg, bg)


def label(pair: dict) -> str:
    """The pair written as tokens, such as "success on success 12% over surface"."""
    if "tint" not in pair:
        return f"`{pair['fg']}` on `{pair['bg']}`"
    return f"`{pair['fg']}` on `{pair.get('tintOf', pair['fg'])}` {round(pair['tint'] * 100)}% over `{pair['bg']}`"


def report(tokens: dict, pairs: dict) -> tuple[str, int]:
    """Build the Markdown report and count the failing pairs."""
    lines = [
        "# Contrast report",
        "",
        "GENERATED by `tools/contrast-check/check_contrast.py` from `packages/design-tokens/tokens.json`"
        " and `tools/contrast-check/pairs.json`. Do not edit; run the check again instead.",
        "",
        "WCAG 2.2 AA: 4.5:1 for text, 3:1 for icons, field outlines, focus rings and chart marks.",
        "",
        "| Used for | Pair | Light | Dark | Needs |",
        "| --- | --- | --- | --- | --- |",
    ]
    failures = 0
    # Step 1: every required pair, both modes side by side.
    for pair in pairs["pairs"]:
        cells = []
        for mode in MODES:
            _, _, r = check(tokens["color"][mode], pair)
            ok = r >= pair["min"]
            failures += not ok
            cells.append(f"{r:.2f} {'pass' if ok else '**FAIL**'}")
        lines.append(f"| {pair['use']} | {label(pair)} | {cells[0]} | {cells[1]} | {pair['min']}:1 |")
    # Step 2: decorative pairs, shown for the record but not required.
    lines += ["", "## Decorative (no minimum)", "", "| Used for | Pair | Light | Dark |", "| --- | --- | --- | --- |"]
    for pair in pairs["decorative"]:
        values = [f"{check(tokens['color'][m], pair)[2]:.2f}" for m in MODES]
        lines.append(f"| {pair['use']} | {label(pair)} | {values[0]} | {values[1]} |")
    lines += ["", f"**Result:** {len(pairs['pairs']) * 2 - failures} of {len(pairs['pairs']) * 2} checks pass."]
    return "\n".join(lines) + "\n", failures


def main(root: Path) -> int:
    """Run the check, write the report and return 1 if anything fails."""
    tokens = json.loads((root / "packages/design-tokens/tokens.json").read_text(encoding="utf-8"))
    pairs = json.loads((root / "tools/contrast-check/pairs.json").read_text(encoding="utf-8"))
    text, failures = report(tokens, pairs)
    (root / "docs/design/contrast-report.md").write_text(text, encoding="utf-8")
    print(f"{failures} failing checks. Report: docs/design/contrast-report.md")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1] if len(sys.argv) > 1 else ".")))
