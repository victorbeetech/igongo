#!/usr/bin/env python3
"""
Builds the seed data for the core back end from the specs, so the database
always matches the docs:

  packages/contracts/catalog/modules.json         the 84 modules (key, number, name, group)
  modules/roles-permissions/seed/premade-roles.json  the 121 pre-made roles
  modules/roles-permissions/migrations/<n>_seed_premade_roles.sql  the same roles as SQL

Run from the repository root after changing docs/modules or docs/roles:

  python3 tools/roles-seed/gen_roles_seed.py

The SQL uses ON CONFLICT DO NOTHING, so it never overwrites changes the super
admin has made to a role in the live system.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
MODULES_DIR = ROOT / "docs" / "modules"
ROLES_DIR = ROOT / "docs" / "roles"
SQL_OUT = ROOT / "modules" / "roles-permissions" / "migrations" / "0001_seed_premade_roles.sql"

# The roles spec's data scope words, mapped to the database values.
SCOPES = {
    "Everything": "all",
    "Own location": "location",
    "Own department": "department",
    "Own team": "team",
    "Assigned to them": "assigned",
    "Own records": "own",
    "Public items": "public",
}
# Levels whose people are not staff (no client-view switch, no staff base role).
NON_STAFF_LEVELS = {"Guests and clients", "Partners and suppliers"}


def read_modules():
    """Every module spec: its key, number, name and group."""
    modules = []
    for path in sorted(MODULES_DIR.glob("[0-9][0-9]-*.md")):
        text = path.read_text()
        title = re.search(r"^# (\d+)\. (.+)$", text, re.M)
        meta = re.search(r"\*\*Group:\*\* (.+?) · \*\*Module key:\*\* `([^`]+)`", text)
        modules.append({"number": int(title.group(1)), "key": meta.group(2), "name": title.group(2).strip(), "group": meta.group(1).strip(), "file": path.name})
    return modules


def section(text, heading):
    """The lines under a `## heading`, up to the next heading."""
    match = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return match.group(1) if match else ""


def bullets(block):
    """The `- item` lines of a block."""
    return [line[2:].strip() for line in block.splitlines() if line.startswith("- ")]


def read_role(path, module_key_by_file):
    """One role file as a dict."""
    text = path.read_text()
    name = re.search(r"^# (.+)$", text, re.M).group(1).strip()
    meta = re.search(r"\*\*Level:\*\* (.+?) · \*\*Role key:\*\* `([^`]+)`", text)
    level, key = meta.group(1).strip(), meta.group(2)
    purpose = section(text, "Purpose").split("**Reports to:**")[0].split("**Uses:**")[0].strip()
    reports = re.search(r"\*\*Reports to:\*\* \[[^\]]+\]\(([^)]+)\.md\)", text)
    includes = re.findall(r"Includes everything in the \[[^\]]+\]\(([^)]+)\.md\)", text)
    permissions = []
    for row in re.finditer(r"^\| \[[^\]]+\]\(\.\./modules/([^)]+)\) \| ([^|]+) \| ([^|]+) \|$", section(text, "Modules, screens and default permissions"), re.M):
        module = module_key_by_file[row.group(1)]
        scope = SCOPES[row.group(3).strip()]
        for action in [a.strip() for a in row.group(2).split(",") if a.strip()]:
            permissions.append({"key": f"{module}.*.{action}", "scope": scope})
    return {
        "key": key,
        "name": name,
        "level": level,
        "description": purpose,
        "isStaff": level not in NON_STAFF_LEVELS,
        "reportsTo": reports.group(1) if reports else None,
        "includes": includes,
        "homeTiles": bullets(section(text, "Home screen tiles")),
        "approvalLimits": bullets(section(text, "Approval limits")),
        "extraRules": bullets(section(text, "Extra rules")),
        "permissions": permissions,
    }


def sql_text(value):
    """A Postgres string literal, or NULL."""
    return "NULL" if value is None else "'" + value.replace("'", "''") + "'"


def write_sql(roles):
    """The seed as SQL: roles, then permissions, then included roles."""
    out = ["-- Seeds the 121 pre-made roles from docs/roles. GENERATED by",
           "-- tools/roles-seed/gen_roles_seed.py: do not edit by hand.",
           "-- ON CONFLICT DO NOTHING keeps any change the super admin made."]
    for r in roles:
        rules = json.dumps({"approvalLimits": r["approvalLimits"], "extraRules": r["extraRules"]})
        out.append(
            'INSERT INTO "roles"."roles" ("id","key","name","description","level","is_staff","is_premade","home_tiles","rules") VALUES ('
            f"{sql_text('role_' + r['key'])},{sql_text(r['key'])},{sql_text(r['name'])},{sql_text(r['description'])},{sql_text(r['level'])},"
            f"{'true' if r['isStaff'] else 'false'},true,{sql_text(json.dumps(r['homeTiles']))}::jsonb,{sql_text(rules)}::jsonb) ON CONFLICT DO NOTHING;"
        )
    for r in roles:
        if r["reportsTo"]:
            out.append(f'UPDATE "roles"."roles" SET "reports_to_role_id" = {sql_text("role_" + r["reportsTo"])} WHERE "id" = {sql_text("role_" + r["key"])} AND "reports_to_role_id" IS NULL;')
        for p in r["permissions"]:
            out.append(f'INSERT INTO "roles"."role_permissions" ("role_id","permission_key","scope") VALUES ({sql_text("role_" + r["key"])},{sql_text(p["key"])},{sql_text(p["scope"])}) ON CONFLICT DO NOTHING;')
        for inc in r["includes"]:
            out.append(f'INSERT INTO "roles"."role_includes" ("role_id","included_role_id") VALUES ({sql_text("role_" + r["key"])},{sql_text("role_" + inc)}) ON CONFLICT DO NOTHING;')
    SQL_OUT.write_text("\n--> statement-breakpoint\n".join(out) + "\n")


def main():
    modules = read_modules()
    by_file = {m["file"]: m["key"] for m in modules}
    roles = [read_role(p, by_file) for p in sorted(ROLES_DIR.glob("*.md")) if p.name != "README.md"]
    (ROOT / "packages" / "contracts" / "catalog" / "modules.json").write_text(json.dumps([{k: m[k] for k in ("number", "key", "name", "group")} for m in modules], indent=2) + "\n")
    seed_dir = ROOT / "modules" / "roles-permissions" / "seed"
    seed_dir.mkdir(parents=True, exist_ok=True)
    (seed_dir / "premade-roles.json").write_text(json.dumps(roles, indent=2) + "\n")
    write_sql(roles)
    print(f"{len(modules)} modules, {len(roles)} roles, {sum(len(r['permissions']) for r in roles)} permissions")


if __name__ == "__main__":
    main()
